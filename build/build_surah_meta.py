"""
Regenerates surah-meta.js — the small, static per-surah reference data the app
needs at boot (names, ayah counts, which page each surah starts on, whether it
has a Bismillah line). The Qur'an text/page-layout itself is fetched live per
page from api.quran.com at runtime (see quran-api.js) — this script only
covers the tiny bit of metadata that's the same for everyone and barely ever
changes, so there's no reason to fetch it on every page load.

Requires internet and Python 3, no other dependencies. Only needs to be
re-run if surah metadata ever needs refreshing — not part of the app's normal
runtime path.

Usage:
    python build/build_surah_meta.py
Writes ../surah-meta.js (i.e. the project root's surah-meta.js) that
index.html loads via <script src="surah-meta.js">.
"""
import json
import os
import urllib.request

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_ROOT = os.path.dirname(SCRIPT_DIR)
OUT_PATH = os.path.join(PROJECT_ROOT, "surah-meta.js")


def fetch_json(url):
    # api.quran.com 403s on Python's default urllib User-Agent
    req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
    with urllib.request.urlopen(req) as resp:
        return json.load(resp)


def main():
    meta = fetch_json("https://api.alquran.cloud/v1/meta")["data"]
    chapters = fetch_json("https://api.quran.com/api/v4/chapters?language=en")["chapters"]

    first_page_by_number = {c["id"]: c["pages"][0] for c in chapters}
    bismillah_pre_by_number = {c["id"]: c["bismillah_pre"] for c in chapters}
    assert len(first_page_by_number) == 114

    # [number, arabicName, englishName, englishTranslation, isMeccan, ayahCount, firstPage, hasBismillah]
    surah_meta_out = [
        [
            s["number"], s["name"], s["englishName"], s["englishNameTranslation"],
            1 if s["revelationType"] == "Meccan" else 0, s["numberOfAyahs"],
            first_page_by_number[s["number"]], bismillah_pre_by_number[s["number"]],
        ]
        for s in meta["surahs"]["references"]
    ]
    assert len(surah_meta_out) == 114

    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Auto-generated by build/build_surah_meta.py. Do not hand-edit — re-run the script instead.\n")
        f.write("const SURAH_META=" + json.dumps(surah_meta_out, ensure_ascii=False, separators=(",", ":")) + ";\n")

    print("wrote", OUT_PATH, "(%.1f KB)" % (os.path.getsize(OUT_PATH) / 1024))


if __name__ == "__main__":
    main()
