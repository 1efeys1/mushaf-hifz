// Regenerates ayah-page.js — the static surah:ayah → mushaf-page-number table used by the
// sidebar's "jump to ayah" feature (app.js goToAyah). Nothing at runtime can derive this:
// SURAH_META only knows each surah's FIRST page, and the runtime page cache only covers
// pages the user has already visited. One build-time sweep of all 604 pages gives the full
// 6236-entry mapping (~20KB), same spirit as build_surah_meta.py's static metadata.
//
// Requires internet and bun (or node 18+), no other dependencies. Only re-run if the
// page layout ever changes (the runtime pins the 16-line Madani edition via mushaf=2 /
// code_v2 — see quran-api.js — so this table must be generated with the same params).
//
// Usage:
//     bun build/build_ayah_page.js
// Writes ../ayah-page.js (project root) that index.html loads via
// <script src="ayah-page.js">.

const OUT_PATH = new URL("../ayah-page.js", import.meta.url);
const TOTAL_PAGES = 604;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function fetchJson(url, attempt = 1) {
  // api.quran.com 403s non-browser User-Agents (see build_surah_meta.py)
  const res = await fetch(url, { headers: { "User-Agent": "Mozilla/5.0" } });
  if (!res.ok) {
    if (attempt < 3) {
      await sleep(1500 * attempt);
      return fetchJson(url, attempt + 1);
    }
    throw new Error(`HTTP ${res.status} for ${url}`);
  }
  return res.json();
}

async function main() {
  // surah-meta.js has no exports — evaluate it in a function scope to get the constant
  const fs = await import("node:fs");
  const { fileURLToPath } = await import("node:url");
  const metaSrc = fs.readFileSync(fileURLToPath(new URL("../surah-meta.js", import.meta.url)), "utf8");
  const SURAH_META = new Function(metaSrc + "\nreturn SURAH_META;")();

  // AYAH_PAGE[surah-1][ayah-1] = page
  const table = SURAH_META.map((s) => new Array(s[5]).fill(0));
  let filled = 0;

  for (let page = 1; page <= TOTAL_PAGES; page++) {
    const url = `https://api.quran.com/api/v4/verses/by_page/${page}` +
      `?fields=verse_key&mushaf=2&per_page=all`;
    const data = await fetchJson(url);
    const verses = data && data.verses;
    if (!Array.isArray(verses) || !verses.length) throw new Error(`page ${page} returned no verses`);
    for (const v of verses) {
      const m = /^(\d+):(\d+)$/.exec(v.verse_key);
      if (!m) throw new Error(`bad verse_key "${v.verse_key}" on page ${page}`);
      const s = +m[1], a = +m[2];
      const row = table[s - 1];
      if (!row || a > row.length) throw new Error(`verse ${v.verse_key} exceeds SURAH_META bounds`);
      row[a - 1] = page;
      filled++;
    }
    if (page % 50 === 0) console.log(`  …page ${page}/604`);
    await sleep(50);
  }

  // sanity pass — mismatches print as warnings (the table is ground truth from the same
  // endpoint family the runtime renders), but coverage/monotonicity must hold
  let warnings = 0;
  if (filled !== 6236) throw new Error(`coverage ${filled} != 6236`);
  table.forEach((row, i) => {
    const meta = SURAH_META[i];
    const label = `${meta[0]}. ${meta[2]}`;
    if (row.some((p) => !p)) throw new Error(`${label} has unfilled ayah slots`);
    for (let a = 1; a < row.length; a++) {
      if (row[a] < row[a - 1]) throw new Error(`${label} page numbers not monotonic at ayah ${a + 1}`);
    }
    if (row[0] !== meta[6]) {
      console.warn(`  warning: ${label} first page ${row[0]} != SURAH_META firstPage ${meta[6]}`);
      warnings++;
    }
  });

  const out = "// Auto-generated by build/build_ayah_page.js. Do not hand-edit — re-run the script instead.\n" +
    "// AYAH_PAGE[surah-1][ayah-1] = mushaf page number (16-line Madani edition).\n" +
    "const AYAH_PAGE=" + JSON.stringify(table) + ";\n";
  fs.writeFileSync(fileURLToPath(OUT_PATH), out);
  console.log(`wrote ${fileURLToPath(OUT_PATH)} (${(fs.statSync(fileURLToPath(OUT_PATH)).size / 1024).toFixed(1)} KB, ` +
    `${filled} ayah entries, ${warnings} warnings)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
